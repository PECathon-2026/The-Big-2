"""Honor: points for observations that the sky actually allowed, ranks, and a personal ledger."""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field

from ..core.http import ProviderError
from ..lens import jobs as lens_jobs
from ..watchtower import openmeteo
from ..watchtower.score import compute_night_score
from . import rules, store

router = APIRouter()


class ObserveBody(BaseModel):
    user_id: str = Field(min_length=3, max_length=64, description="Anonymous id generated by the client and kept in local storage")
    lat: float = Field(ge=-90, le=90)
    lon: float = Field(ge=-180, le=180)
    kind: str = Field("custom", description="moon | planet | meteor | satellite | launch | eclipse | deepsky | custom")
    event_id: str | None = Field(None, description="An id from /api/scroll/events; when given, the claim is checked against that event's window")
    title: str | None = None
    note: str | None = Field(None, max_length=500)
    claimed_at: datetime | None = Field(None, description="When you observed (ISO). Defaults to now.")
    photo_job_id: str | None = Field(None, description="A finished Lens job id; a solved WCS earns the photo bonus")


@router.get("/ranks")
async def ranks():
    return {"ranks": [{"at": r[0], "kanji": r[1], "romaji": r[2], "meaning": r[3]} for r in rules.RANKS], "points": rules.POINTS, "photo_bonus": rules.PHOTO_BONUS}


@router.post("/observe", status_code=201)
async def observe(body: ObserveBody):
    """Log an observation. It is verified against the sky before any points are awarded."""
    kind = body.kind if body.kind in rules.POINTS else "custom"
    claimed_at = (body.claimed_at or datetime.now(timezone.utc))
    if claimed_at.tzinfo is None:
        claimed_at = claimed_at.replace(tzinfo=timezone.utc)
    if claimed_at > datetime.now(timezone.utc):
        raise HTTPException(400, "claimed_at is in the future; you cannot log what you have not seen yet")

    verified, reason, evidence = await rules.verify(body.lat, body.lon, kind, body.event_id, claimed_at)
    points = rules.POINTS[kind] if verified else 0

    photo: dict[str, Any] | None = None
    if body.photo_job_id:
        job = lens_jobs.get_job(body.photo_job_id)
        if job is None or job.status != "done" or job.result is None:
            raise HTTPException(400, "photo_job_id must be a finished Lens job")
        solved = bool(job.result.wcs.solved)
        photo = {"job_id": job.id, "wcs_solved": solved, "detections": len(job.result.detections)}
        if verified and solved:
            points += rules.PHOTO_BONUS
            reason += f"; photo verified ({job.result.wcs.method} WCS), +{rules.PHOTO_BONUS}"
        elif verified:
            reason += "; photo attached but not plate-solved, no bonus"
        evidence["photo"] = photo

    conditions = None
    try:  # snapshot of the conditions at the claimed hour, for the journal
        fc, _ = await openmeteo.forecast([(body.lat, body.lon)], days=2)
        ns = compute_night_score(body.lat, body.lon, fc[0], None, None, None, ref=claimed_at)
        h = min(ns.hours, key=lambda h: abs((h.time - claimed_at).total_seconds()), default=None)
        if h and abs((h.time - claimed_at).total_seconds()) <= 3600:
            conditions = {"score": h.score, "cloud_low": h.cloud_low, "humidity": h.humidity, "moon_illum": h.moon_illum, "time_local": h.time_local}
    except (ProviderError, Exception):  # noqa: BLE001 - the ledger must not depend on the weather provider
        conditions = None

    title = body.title or (evidence.get("event") or f"{kind} observation")
    row = store.add(
        body.user_id, kind=kind, event_id=body.event_id, title=title, note=body.note, lat=body.lat, lon=body.lon,
        claimed_at=claimed_at.isoformat(), verified=verified, reason=reason, evidence=evidence, points=points,
        photo_job_id=body.photo_job_id, conditions=conditions,
    )
    total = store.total_points(body.user_id)
    return {"observation": row, "accepted": verified, "points_awarded": points, "reason": reason, "rank": rules.rank_for(total)}


@router.get("/ledger")
async def ledger(user_id: str = Query(..., min_length=3, max_length=64)):
    entries = store.ledger(user_id)
    total = store.total_points(user_id)
    return {
        "user_id": user_id,
        "rank": rules.rank_for(total),
        "verified_count": sum(1 for e in entries if e["verified"]),
        "rejected_count": sum(1 for e in entries if not e["verified"]),
        "entries": entries,
    }
