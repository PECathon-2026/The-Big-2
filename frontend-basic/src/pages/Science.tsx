import { useMemo, useState } from 'react';
import { API_BASE, ApiError, buildUrl } from '../api';
import { Card } from '../components/Card';
import { Controls } from '../components/Controls';
import { JsonView } from '../components/JsonView';
import { ErrorBox } from '../components/Status';
import { useApp } from '../context/AppContext';

interface Endpoint {
  path: string;
  desc: string;
  params?: Record<string, string | number | boolean | undefined>;
  kind?: 'json' | 'text';
}

interface CallState {
  status: 'idle' | 'loading' | 'ok' | 'error';
  body?: unknown;
  error?: Error;
  ms?: number;
  http?: number;
  url?: string;
}

/** Lists every GET endpoint and lets the backend owner inspect the raw response for the current location/time. */
export default function Science() {
  const { lat, lon, atIso } = useApp();
  const [calls, setCalls] = useState<Record<string, CallState>>({});

  const endpoints = useMemo<Endpoint[]>(() => {
    const q = { lat, lon };
    const now = new Date(atIso);
    return [
      { path: '/api/health', desc: 'Service health, version, demo replay flag, astrometry enabled' },
      { path: '/api/watchtower/forecast', desc: 'Raw hourly forecast (Open-Meteo) incl. air quality', params: { ...q, days: 2 } },
      { path: '/api/watchtower/score', desc: 'Night Honor Score with trace and best window', params: { ...q, at: atIso, window_hours: 2, light_pollution: true } },
      { path: '/api/watchtower/light-pollution', desc: 'VIIRS Black Marble radiance → Bortle estimate', params: q },
      { path: '/api/watchtower/spots', desc: 'Ranked observing spots within radius (slow: Overpass + per-spot score)', params: { ...q, radius_km: 60, limit: 12, at: atIso } },
      { path: '/api/scroll/moon', desc: 'Moon phase, Japanese name, rise/set, libration', params: { ...q, at: atIso } },
      { path: '/api/scroll/sun', desc: 'Sun altitude and twilight times', params: { ...q, at: atIso } },
      { path: '/api/scroll/eclipses', desc: 'Upcoming lunar/solar eclipses with local visibility', params: { ...q, start: atIso, lunar: 3, solar: 2 } },
      { path: '/api/scroll/meteors', desc: 'Active showers with hourly rate from here', params: { ...q, at: atIso } },
      { path: '/api/scroll/passes', desc: 'ISS passes with track', params: { ...q, days: 3, sat: 'ISS', min_alt: 10, start: atIso } },
      { path: '/api/scroll/launches', desc: 'Rocket launches (Launch Library 2)', params: { ...q, limit: 20 } },
      { path: '/api/scroll/planets', desc: 'Planet positions, magnitudes, rise/set', params: { ...q, at: atIso } },
      { path: '/api/scroll/calendar', desc: 'Lunisolar calendar for the month', params: { ...q, year: now.getFullYear(), month: now.getMonth() + 1 } },
      { path: '/api/scroll/season', desc: '24 sekki + 72 kō for the reference time', params: { at: atIso } },
      { path: '/api/scroll/events', desc: 'Unified event list (moon, meteor, eclipse, satellite, launch, planet)', params: { ...q, days: 7, start: atIso } },
      {
        path: '/api/scroll/ics',
        desc: 'Calendar (.ics) export — text/calendar',
        params: { title: 'Tsukuyomi test event', start: atIso, description: 'generated by frontend-basic', location: `${lat},${lon}` },
        kind: 'text',
      },
      { path: '/api/lens/samples', desc: 'Sample images for the Spirit Lens' },
    ];
  }, [lat, lon, atIso]);

  const call = async (ep: Endpoint) => {
    const url = buildUrl(ep.path, ep.params);
    setCalls((c) => ({ ...c, [ep.path]: { status: 'loading', url } }));
    const t0 = performance.now();
    try {
      const res = await fetch(url);
      const text = await res.text();
      let body: unknown = text;
      try {
        body = JSON.parse(text);
      } catch {
        /* keep text */
      }
      const ms = Math.round(performance.now() - t0);
      if (!res.ok) throw new ApiError(res.status, url, body);
      setCalls((c) => ({ ...c, [ep.path]: { status: 'ok', body, ms, http: res.status, url } }));
    } catch (e) {
      const err = e instanceof Error ? e : new Error(String(e));
      setCalls((c) => ({ ...c, [ep.path]: { status: 'error', error: err, ms: Math.round(performance.now() - t0), url } }));
    }
  };

  return (
    <main className="page">
      <div className="page-title">
        <h1>Science</h1>
        <span className="jp">理</span>
        <span className="sub">every endpoint, raw · base {API_BASE}</span>
      </div>
      <Controls />
      <Card en="Endpoints" jp="接点" right={<button className="btn small" onClick={() => endpoints.forEach((e) => void call(e))}>Call all</button>}>
        {endpoints.map((ep) => {
          const st = calls[ep.path] ?? { status: 'idle' };
          return (
            <div className="endpoint" key={ep.path}>
              <div className="p">
                <code>GET</code> {ep.path}
                {ep.params && (
                  <span className="muted small" style={{ marginLeft: 8 }}>
                    {Object.entries(ep.params)
                      .filter(([, v]) => v !== undefined)
                      .map(([k, v]) => `${k}=${v}`)
                      .join('&')}
                  </span>
                )}
              </div>
              <div className="row">
                {st.ms !== undefined && (
                  <span className="muted small num">
                    {st.http ? `HTTP ${st.http} · ` : ''}
                    {st.ms} ms
                  </span>
                )}
                <button className="btn small" onClick={() => void call(ep)} disabled={st.status === 'loading'}>
                  {st.status === 'loading' ? 'Calling…' : 'Call'}
                </button>
                {st.url && (
                  <a className="small" href={st.url} target="_blank" rel="noreferrer">
                    open
                  </a>
                )}
              </div>
              <div className="d">{ep.desc}</div>
              {st.status === 'ok' && (
                <div className="out">
                  <JsonView value={st.body} open={true} label="response" />
                </div>
              )}
              {st.status === 'error' && st.error && (
                <div className="out">
                  <ErrorBox error={st.error} onRetry={() => void call(ep)} />
                </div>
              )}
            </div>
          );
        })}
      </Card>
      <p className="muted small" style={{ marginTop: 14 }}>
        Lens POST endpoints (<code>/api/lens/jobs</code>, <code>/benchmark</code>, <code>/solve</code>) are exercised from the Lens page; image endpoints return PNG.
      </p>
    </main>
  );
}
